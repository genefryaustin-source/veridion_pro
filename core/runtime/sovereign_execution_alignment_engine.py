    def _record_verdict(
        self,
        verdict: SovereignExecutionAlignmentVerdict,
        *,
        context: Optional[Dict[str, Any]] = None,
    ) -> None:
        self._verdicts.append(verdict)

        self._write_to_operational_memory(verdict, context=context)
        self._write_to_lineage(verdict, context=context)
        self._emit_event(verdict, context=context)

    def _write_to_operational_memory(
        self,
        verdict: SovereignExecutionAlignmentVerdict,
        *,
        context: Optional[Dict[str, Any]] = None,
    ) -> None:
        memory = self.operational_memory_engine
        if memory is None:
            return

        payload = {
            "type": "SOVEREIGN_EXECUTION_ALIGNMENT_VERDICT",
            "verdict": self._verdict_to_dict(verdict),
            "context": context or {},
        }

        try:
            if hasattr(memory, "append_memory"):
                memory.append_memory(payload)
            elif hasattr(memory, "record"):
                memory.record(payload)
            elif hasattr(memory, "write"):
                memory.write(payload)
        except Exception as exc:
            print(f"⚠️ Execution alignment memory write failed: {exc}")

    def _write_to_lineage(
        self,
        verdict: SovereignExecutionAlignmentVerdict,
        *,
        context: Optional[Dict[str, Any]] = None,
    ) -> None:
        lineage = self.lineage_engine
        if lineage is None:
            return

        payload = {
            "type": "SOVEREIGN_EXECUTION_ALIGNMENT_VERDICT",
            "verdict": self._verdict_to_dict(verdict),
            "context": context or {},
        }

        try:
            if hasattr(lineage, "record_lineage"):
                lineage.record_lineage(payload)
            elif hasattr(lineage, "append_lineage"):
                lineage.append_lineage(payload)
            elif hasattr(lineage, "record"):
                lineage.record(payload)
        except Exception as exc:
            print(f"⚠️ Execution alignment lineage write failed: {exc}")

    def _emit_event(
        self,
        verdict: SovereignExecutionAlignmentVerdict,
        *,
        context: Optional[Dict[str, Any]] = None,
    ) -> None:
        if self.event_bus is None:
            return

        payload = {
            "event_type": "SOVEREIGN_EXECUTION_ALIGNMENT_VERDICT",
            "engine": self.engine_name,
            "verdict": self._verdict_to_dict(verdict),
            "context": context or {},
        }

        try:
            if hasattr(self.event_bus, "emit"):
                self.event_bus.emit(
                    "SOVEREIGN_EXECUTION_ALIGNMENT_VERDICT",
                    payload,
                )
            elif hasattr(self.event_bus, "publish"):
                self.event_bus.publish(
                    "SOVEREIGN_EXECUTION_ALIGNMENT_VERDICT",
                    payload,
                )
        except Exception as exc:
            print(f"⚠️ Execution alignment event emit failed: {exc}")

