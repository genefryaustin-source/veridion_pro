    @staticmethod
    def _safe_autonomy_mode(value: Any) -> str:
        value = str(value or AutonomyMode.SUPERVISED_AUTONOMY.value).upper()
        valid = {item.value for item in AutonomyMode}
        return value if value in valid else AutonomyMode.SUPERVISED_AUTONOMY.value

    @staticmethod
    def _safe_action_type(value: Any) -> str:
        value = str(value or ExecutionActionType.UNKNOWN.value).upper()
        valid = {item.value for item in ExecutionActionType}
        return value if value in valid else ExecutionActionType.UNKNOWN.value

    @staticmethod
    def _safe_domain(value: Any) -> str:
        value = str(value or AlignmentDomain.UNKNOWN.value).upper()
        valid = {item.value for item in AlignmentDomain}
        return value if value in valid else AlignmentDomain.UNKNOWN.value

    @staticmethod
    def _safe_severity(value: Any) -> str:
        value = str(value or SEVERITY_INFO).upper()
        valid = {
            SEVERITY_INFO,
            SEVERITY_LOW,
            SEVERITY_MEDIUM,
            SEVERITY_HIGH,
            SEVERITY_CRITICAL,
        }
        return value if value in valid else SEVERITY_INFO

    @staticmethod
    def _clamp_confidence(value: Any) -> float:
        try:
            score = float(value)
        except Exception:
            score = 0.0

        return max(0.0, min(1.0, score))


