"""
core/runtime/sovereign_execution_alignment_engine.py

Sovereign Execution Alignment Engine

Strategic execution validator between:

    sovereign decision fabric
        ↓
    execution alignment
        ↓
    governance approval / execution router / connector fabric

IMPORTANT:
This engine DOES NOT execute actions.

It does NOT:
- call Microsoft Graph
- isolate endpoints
- revoke sessions
- quarantine mailboxes
- delete emails
- mutate external systems

It ONLY determines:
- whether execution should proceed
- under what governance conditions
- whether approval is required
- whether rollback/continuity review is required
- whether the action must be blocked or deferred
"""

